# No Light After Midnight - yağmur damlası materyali (/Game/FX/NL/M_NLRain)
# Işıktan etkilenen yarı saydam materyal: fenerle bakınca damlalar parlar. ISM (instanced) ile kullanılır.
# Parametreler: Color, Glow (ışıksız da hafif görünsün), Opacity, Fade (kod yağmur başlarken/dinerken 0..1 verir)
# Çalıştırma: UnrealEditor-Cmd.exe NoLightAfterMidnight.uproject -run=pythonscript -script="<tam yol>\Scripts\nl_make_rain.py"
import unreal

PATH = "/Game/FX/NL/M_NLRainSoft"
mel = unreal.MaterialEditingLibrary
if unreal.EditorAssetLibrary.does_asset_exist(PATH):
    unreal.EditorAssetLibrary.delete_asset(PATH)
M = unreal.AssetToolsHelpers.get_asset_tools().create_asset("M_NLRainSoft", "/Game/FX/NL", unreal.Material, unreal.MaterialFactoryNew())
M.set_editor_property("blend_mode", unreal.BlendMode.BLEND_TRANSLUCENT)
M.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_DEFAULT_LIT)
M.set_editor_property("translucency_lighting_mode", unreal.TranslucencyLightingMode.TLM_SURFACE_PER_PIXEL_LIGHTING)
M.set_editor_property("used_with_instanced_static_meshes", True)

col = mel.create_material_expression(M, unreal.MaterialExpressionVectorParameter, -800, -200)
col.set_editor_property("parameter_name", "Color")
col.set_editor_property("default_value", unreal.LinearColor(0.62, 0.68, 0.78, 1.0))
glow = mel.create_material_expression(M, unreal.MaterialExpressionScalarParameter, -800, 0)
glow.set_editor_property("parameter_name", "Glow")
glow.set_editor_property("default_value", 0.05)
op = mel.create_material_expression(M, unreal.MaterialExpressionScalarParameter, -800, 200)
op.set_editor_property("parameter_name", "Opacity")
op.set_editor_property("default_value", 0.35)
fd = mel.create_material_expression(M, unreal.MaterialExpressionScalarParameter, -800, 350)
fd.set_editor_property("parameter_name", "Fade")
fd.set_editor_property("default_value", 1.0)
rough = mel.create_material_expression(M, unreal.MaterialExpressionConstant, -800, 500)
rough.set_editor_property("r", 0.15)

em = mel.create_material_expression(M, unreal.MaterialExpressionMultiply, -450, -50)
mel.connect_material_expressions(col, "", em, "A")
mel.connect_material_expressions(glow, "", em, "B")
opm = mel.create_material_expression(M, unreal.MaterialExpressionMultiply, -450, 250)
mel.connect_material_expressions(op, "", opm, "A")
mel.connect_material_expressions(fd, "", opm, "B")

mel.connect_material_property(col, "", unreal.MaterialProperty.MP_BASE_COLOR)
mel.connect_material_property(em, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)
# Kameraya çok yakın damlalar söner (ekranda iri çizgi olmasın)
pd = mel.create_material_expression(M, unreal.MaterialExpressionPixelDepth, -800, 650)
sub = mel.create_material_expression(M, unreal.MaterialExpressionSubtract, -650, 650)
mel.connect_material_expressions(pd, "", sub, "A")
c60 = mel.create_material_expression(M, unreal.MaterialExpressionConstant, -800, 750)
c60.set_editor_property("r", 70.0)
mel.connect_material_expressions(c60, "", sub, "B")
dv = mel.create_material_expression(M, unreal.MaterialExpressionDivide, -500, 650)
mel.connect_material_expressions(sub, "", dv, "A")
c300 = mel.create_material_expression(M, unreal.MaterialExpressionConstant, -650, 750)
c300.set_editor_property("r", 350.0)
mel.connect_material_expressions(c300, "", dv, "B")
sat = mel.create_material_expression(M, unreal.MaterialExpressionSaturate, -380, 650)
mel.connect_material_expressions(dv, "", sat, "")
opn = mel.create_material_expression(M, unreal.MaterialExpressionMultiply, -250, 400)
mel.connect_material_expressions(opm, "", opn, "A")
mel.connect_material_expressions(sat, "", opn, "B")
mel.connect_material_property(opn, "", unreal.MaterialProperty.MP_OPACITY)
mel.connect_material_property(rough, "", unreal.MaterialProperty.MP_ROUGHNESS)
mel.recompile_material(M)
unreal.EditorAssetLibrary.save_loaded_asset(M)
unreal.log("NLRain: created " + PATH)
